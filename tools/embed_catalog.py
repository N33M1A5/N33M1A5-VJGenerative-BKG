#!/usr/bin/env python3
"""Embed the reviewed GLSL sources for the isolated FFGL development build."""
from pathlib import Path
import re,json,unicodedata
ROOT=Path(__file__).resolve().parents[1]
SRC=ROOT/'prototypes/gate_a'
output=ROOT/'src/v17/generated_shaders.h'
common=(SRC/'common.glsl').read_text().replace('vec3 finishLight(vec3 c){','vec3 sourceLight(vec3 c){')
extra=(ROOT/'palettes_extra.h').read_text().split('R"GLSL(')[1].split(')GLSL"')[0]
legacy=(ROOT/'shaders_expansion.h').read_text()
original=legacy[legacy.index('vec3 palOriginal(float t){'):legacy.index('// User-definable palette.')]
adapter='''
uniform float uPalette,uHue,uColorSource,uRGBAType,uRGBABlend,uRGBAMix,uHostBeat,uHostPulse;
uniform vec4 uRGBA_A,uRGBA_B;
'''+extra+original+'''
vec3 finishLight(vec3 c){
 c=sourceLight(c);
 float chroma=max(max(c.r,c.g),c.b)-min(min(c.r,c.g),c.b);
 float neutralTint=(1.-smoothstep(.001,.06,chroma))*max(0.,sin(hue*3.14159265))*.8;
 c*=mix(vec3(1),.35+spectral(hue),neutralTint);
 float l=max(max(c.r,c.g),c.b);
 float p=.18*canvas().y+.10*canvas().x+.25*l;
 int mode=int(uRGBAType+.5);
 if(mode>0 || uColorSource>.5){
  vec3 tint;
  if(mode==0)tint=int(uPalette+.5)>=9?palettePreset(int(uPalette+.5),p):palOriginal(p);
  else if(mode==1)tint=hueShift(uRGBA_A.rgb,uHue);
  else{
   float k=clamp(.5+.5*cos(TAU*(p+uHue+(mode==3?time*.055:0.)))+uRGBAMix-.5,0.,1.);
   int op=int(uRGBABlend+.5);
   if(op==1)tint=clamp(uRGBA_A.rgb+uRGBA_B.rgb*k,0.,1.);
   else if(op==2)tint=1.-(1.-uRGBA_A.rgb)*(1.-uRGBA_B.rgb*k);
   else if(op==3)tint=mix(uRGBA_A.rgb,uRGBA_A.rgb*uRGBA_B.rgb,k);
   else tint=mix(uRGBA_A.rgb,uRGBA_B.rgb,k);
  }
  c=max(tint,0.)*l;
 }
 return c*(1.+uHostPulse*.55*(.5+.5*cos(TAU*uHostBeat)));
}
'''
catalog=json.loads((ROOT/'docs/REFERENCIAS_STORYLOOP.json').read_text())
lib=(ROOT/'engines/library.glsl').read_text()
entries={'kStoryVertex':(SRC/'fullscreen.vert').read_text()}
sources=[]
for ref in catalog['references']:
 eid=ref['engine_id']
 special={13:'flow_dark_glass',19:'spotlight',20:'stained_glass'}
 if eid in special:path=SRC/(special[eid]+'.frag')
 else:
  candidates=list((ROOT/'engines').glob(f'{eid:03d}_*.frag'))
  if len(candidates)!=1:raise ValueError(f'Missing or ambiguous engine {eid}')
  path=candidates[0]
 name=f'kStoryEngine{eid:02d}'
 entries[name]='#version 410 core\nin vec2 uv;out vec4 fragColor;\n'+common+lib+adapter+path.read_text()+'\nvoid main(){fragColor=vec4(scene(),1.); }\n'
 sources.append(name)
 ref['shader_source']=str(path.relative_to(ROOT))
entries['kStoryBloom']=(SRC/'bloom.frag').read_text()
entries['kStoryComposite']=(ROOT/'engines/composite_v17.frag').read_text()
output.write_text('#pragma once\n// Generated by tools/embed_catalog.py. Edit engine sources, then regenerate.\n'+''.join('static const char* '+k+'=R"VJGLSL('+v+')VJGLSL";\n' for k,v in entries.items())+'static const char* const kStorySources[]={'+','.join(sources)+'};\nstatic constexpr int kStoryCount=75;\n')
names=catalog['core_engines']+[r['name'] for r in catalog['references']]
order=sorted(range(82),key=lambda i:unicodedata.normalize('NFKD',names[i]).casefold())
short={0:'Nevoa',1:'Tunel',2:'Lasers',3:'Celulas',4:'Aurora',5:'Orbes',6:'ParticleWave',12:'Flow Dark',18:'Spotlight 1',19:'SacredGlass'}
labels=[]
for i,name in enumerate(names):
 label=short.get(i,unicodedata.normalize('NFKD',name).encode('ascii','ignore').decode().replace('Grainyents: ','Grainy ').replace('Motion Backgrounds','').replace('Worship Backgrounds','').replace('Visual.Church','VC').replace('TRIR Visual4K 15 Full','TRIR 15').replace('Walls  Names of God Line Add 2','Walls Texto').strip())
 labels.append(label[:14])
metadata='#pragma once\nstatic constexpr int kTotalEngines=82,kMotorRows=14;\n'
metadata+='static const int kMotorUIOrder[]={'+','.join(map(str,order))+'};\n'
metadata+='static const char* const kMotorNames[]={'+','.join(json.dumps(x,ensure_ascii=True) for x in names)+'};\n'
metadata+='static const char* const kMotorLabels[]={'+','.join(json.dumps(x,ensure_ascii=True) for x in labels)+'};\n'
(ROOT/'src/v17/engine_catalog.h').write_text(metadata)
(ROOT/'docs/ENGINE_SOURCES.json').write_text(json.dumps([dict(engine_id=r['engine_id'],name=r['name'],source=r['shader_source'],reference=r['url']) for r in catalog['references']],ensure_ascii=False,indent=2)+'\n')
print('Embedded',len(entries),'GLSL programs')
