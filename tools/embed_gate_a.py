#!/usr/bin/env python3
"""Embed the reviewed GLSL sources for the isolated FFGL development build."""
from pathlib import Path
import re
ROOT=Path(__file__).resolve().parents[1]
SRC=ROOT/'prototypes/gate_a'
output=ROOT/'src/v16/generated_shaders.h'
common=(SRC/'common.glsl').read_text().replace('vec3 finishLight(vec3 c){','vec3 sourceLight(vec3 c){')
extra=(ROOT/'palettes_extra.h').read_text().split('R"GLSL(')[1].split(')GLSL"')[0]
legacy=(ROOT/'shaders_expansion.h').read_text()
original=legacy[legacy.index('vec3 palOriginal(float t){'):legacy.index('// User-definable palette.')]
adapter='''
uniform float uPalette,uHue,uColorSource,uRGBAType,uRGBABlend,uRGBAMix,uHostBeat,uHostPulse;
uniform vec4 uRGBA_A,uRGBA_B;
'''+extra+original+'''
vec3 finishLight(vec3 c){
 c=sourceLight(c);
 float l=max(max(c.r,c.g),c.b);
 float p=.18*canvas().y+.10*canvas().x+.25*l;
 int mode=int(uRGBAType+.5);
 if(mode>0 || uColorSource>.5){
  vec3 tint;
  if(mode==0)tint=int(uPalette+.5)>=9?palettePreset(int(uPalette+.5),p):palOriginal(p);
  else if(mode==1)tint=uRGBA_A.rgb;
  else{
   float k=clamp(.5+.5*cos(TAU*(p+uHue+(mode==3?time*.055:0.)))+uRGBAMix-.5,0.,1.);
   int op=int(uRGBABlend+.5);
   if(op==1)tint=clamp(uRGBA_A.rgb+uRGBA_B.rgb*k,0.,1.);
   else if(op==2)tint=1.-(1.-uRGBA_A.rgb)*(1.-uRGBA_B.rgb*k);
   else if(op==3)tint=mix(uRGBA_A.rgb,uRGBA_A.rgb*uRGBA_B.rgb,k);
   else tint=mix(uRGBA_A.rgb,uRGBA_B.rgb,k);
  }
  c=max(tint,0.)*l;
 }
 return c*(1.+uHostPulse*.55*(.5+.5*cos(TAU*uHostBeat)));
}
'''
entries={'kStoryVertex':(SRC/'fullscreen.vert').read_text()}
for key,name in [('kStoryStained','stained_glass'),('kStorySpotlight','spotlight'),('kStoryFlow','flow_dark_glass')]:
 entries[key]='#version 410 core\nin vec2 uv;out vec4 fragColor;\n'+common+adapter+(SRC/(name+'.frag')).read_text()+'\nvoid main(){fragColor=vec4(scene(),1.);}\n'
entries['kStoryBloom']=(SRC/'bloom.frag').read_text()
entries['kStoryComposite']=(SRC/'composite.frag').read_text().replace('uniform float glow,opacity;','uniform float glow,opacity,contrast;').replace('float d=','c=(c-.5)*exp2((contrast-.5)*2.)+.5;\n float d=')
output.write_text('#pragma once\n// Generated by tools/embed_gate_a.py. Edit prototypes, then regenerate.\n'+''.join('static const char* '+k+'=R"VJGLSL('+v+')VJGLSL";\n' for k,v in entries.items()))
print('Embedded',len(entries),'GLSL programs')
